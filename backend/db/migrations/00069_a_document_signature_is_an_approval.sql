-- Юу бүртгэгдэж байгааг хүснэгт өөрөө хэлдэг болов.
--
-- `document_signatures.signature_hash` нь нэрнийхээ хэлж байгаа зүйл БИШ.
-- Энэ аппын баримтын мөр агуулгагүй — гарчиг, төрөл, төлөв, тэр л байна —
-- тиймээс энд хадгалагдаж байгаа зүйл нь ёслолын лавлагаа: eID дээр
-- `eid_session_<id>`, ДАН дээр `dan_sig_<id>`.
--
-- Тэр нь утгагүй гэсэн үг биш: иргэн хэн болохоо баталж, энэ баримтыг
-- нэрлэсэн хүсэлтийг зөвшөөрсөн, цаг нь бичигдсэн. Гэхдээ агуулгад
-- холбогдоогүй — зөвшөөрлийн дараа баримт өөрчлөгдвөл энэ мөрөн дэх ямар ч
-- утга түүнийг үгүйсгэхгүй.
--
-- Багана нь байрандаа: нэрийг нь солих нь уншиж байгаа клиентүүдийг
-- эвдэнэ. API нь `proof` гэсэн талбар нийтэлж, аль нь болохыг хэлнэ.
-- docs/SIGNING.md-г үз.

-- +goose Up
COMMENT ON COLUMN document_signatures.signature_hash IS
    'Ёслолын лавлагаа (eid_session_… / dan_sig_…), агуулгын хэш БИШ. Энэ апп агуулгагүй тул баталгаажсан зөвшөөрөл бүртгэдэг — ADR 0002.';

COMMENT ON COLUMN document_records.signature_hash IS
    'Хамгийн сүүлийн зөвшөөрлийн ёслолын лавлагаа, агуулгын хэш БИШ — ADR 0002.';

-- +goose Down
COMMENT ON COLUMN document_signatures.signature_hash IS NULL;
COMMENT ON COLUMN document_records.signature_hash IS NULL;
