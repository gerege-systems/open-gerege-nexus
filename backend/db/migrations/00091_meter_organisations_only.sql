-- Хэрэглээний хэмжилтээс хүний гэрийг хасав.
--
-- 00053-ийн `usage_events` бол төлбөр уншигддаг хүснэгт: workspace тус бүрд,
-- хэмжигдэхүүн тус бүрд, өдөрт нэг мөр. 00085 хүнд бүрд workspace өгсөн үеэс
-- эхлэн энэ нь өдөр бүр иргэн тутамд мөр бичиж эхэлсэн — өөрөөр хэлбэл
-- үйлчлүүлэгчийн жагсаалтаар биш, **хүн амаар** өсдөг болсон.
--
-- Тоолох ажлыг өөрийг нь internal/operator/metering зассан: одоо collector-ийн
-- INSERT дээр `kind = 'organisation'` гэсэн нэг холболт байна. Энэ файл нь
-- түүнээс өмнө бичигдчихсэн мөрүүдийг арилгана. Хоёулаа хэрэгтэй: шүүлтүүр нь
-- цаашид бичихээ болино, харин аль хэдийн байгаа мөрүүдийг юу ч устгахгүй —
-- ирээдүйн нийлбэр бүр тэднийг оруулан тоолсоор байх байлаа.
--
-- Устгах нь аюулгүй, учир нь эдгээр мөр хэзээ ч төлбөрийн суурь болж
-- байгаагүй: гэр бол хэн ч захиалаагүй, хэнд ч нэхэмжлээгүй workspace.

-- +goose Up

DELETE FROM registry.usage_events u
 USING registry.tenants t
 WHERE t.id = u.tenant_id
   AND t.kind = 'personal';

-- +goose Down

