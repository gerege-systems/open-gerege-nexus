-- ЮУ БАЙСАН БЭ.
--
-- `staff_pin_credentials`-д `failed_attempts`, `locked_until` хоёр багана
-- 00040-өөс хойш бий. PIN тавихад тэдгээр тэглэгддэг; `Verify` нь
-- `locked_until`-ыг хардаг. Гэвч тэднийг НЭМЭГДҮҮЛДЭГ код репод байхгүй —
-- trigger ч үгүй. Өөрөөр хэлбэл түгжээ хэзээ ч биелдэггүй бөгөөд handler-ийн
-- тайлбарт бичсэн «буруу нууц, түгжигдсэн credential, апп суугаагүй гурвыг нэг
-- хариугаар» гэдгийн хоёр дахь нь оршин байгаагүй.
--
-- Үлдэж байсан ганц хязгаар нь IP-ийн нэвтрэлтийн лимит (минутад 5). Дэлгүүрийн
-- касс бол нэг IP, PIN нь дөрвөн орон байж болно: 10,000 хувилбарыг хоногт
-- 7,200 оролдлогоор туулна.
--
--
-- ЯАГААД ТӨХӨӨРӨМЖ ДЭЭР ТООЛОХ ВЭ.
--
-- PIN дангаараа ирдэг тул аль ажилтных болохыг мэдэх аргагүй: буруу оролдлогыг
-- нэг credential-д онооход хэн нэгэн хажуугийн хүний PIN-ийг санаатай гурав
-- буруу бичээд түүнийг түгжиж чадна. Харин таагаад байгаа нь ТӨХӨӨРӨМЖ бөгөөд
-- тэр нь бидэнд мэдэгддэг: кассны өмнө зогсож байгаа хүн юу оролдсоныг
-- төхөөрөмжийн мөрөнд тоолж, хэт олон болвол тэр төхөөрөмжийг түр хаана.
--
-- Хүнийг биш, машиныг түгждэг тул нэг ажилтны ажил зогсохгүй — кассыг дахин
-- нээхэд арван таван минут хүлээх эсвэл админ credential-ыг нь дахин тавина.

