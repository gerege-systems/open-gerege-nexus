/**
 * Аль тэмдгийг үзүүлэхийг таних тэмдгийн төрөл болон issuer шийднэ.
 *
 * Танихгүй провайдерт null буцаана — дуртай нэгнийх нь тэмдгийг зээлж
 * тавихаас дуудагч талын саармаг дүрс дээр үлдэх нь дээр. Тэмдэг гэдэг
 * "энэ бол тэр байгууллага" гэсэн баталгаа, таамаг биш.
 */
export function ProviderMark({ kind, issuer, className }: { kind: string; issuer?: string; className?: string }) {
  if (kind === "eid") return <EIDMark className={className} />;
  if (issuer?.includes("accounts.google.com")) return <GoogleMark className={className} />;
  return null;
}
