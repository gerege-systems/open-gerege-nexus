#!/usr/bin/env node
/**
 * Writes down every icon name this build of lucide can draw.
 *
 *   npm run icons:export     # after upgrading lucide-react
 *
 * The backend's menus name their icons as strings, and until now the only
 * record of which strings were drawable was a hand-written map in
 * frontend/components/Layout.tsx — which a Go test parsed, because there was
 * nowhere else to ask. The map is gone: lucide resolves names at runtime, so
 * the drawable set is lucide's own and no longer something this repository
 * maintains.
 *
 * Something still has to hold that set, though, or a typo in a Go menu
 * definition becomes a fallback glyph nobody notices. So the set is exported
 * here, from the installed package, and
 * backend/internal/workspace/menu/icons_test.go reads the file. Generated rather
 * than written: an upgrade that renames an icon should move this file, and a
 * diff in it is the honest statement of what a lucide upgrade changed.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { iconNames } from "lucide-react/dynamic.mjs";
import pkg from "lucide-react/package.json" with { type: "json" };

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "..", "..", "backend", "internal", "platform", "menu", "testdata", "lucide-icons.txt");

const body = [
  `# Every icon name lucide-react ${pkg.version} can draw.`,
  "#",
  "# Generated by frontend/scripts/export-lucide-icons.mjs — do not edit.",
  "# Read by TestEveryMenuIconIsDrawnByTheFrontend.",
  ...[...iconNames].sort(),
  "",
].join("\n");

await writeFile(OUT, body, "utf8");
console.log(`Wrote ${iconNames.length} icon names to ${path.relative(process.cwd(), OUT)}`);
