/**
 * Байгууллагын богино нэр (slug): нэрнээс санал болгох ба бичсэнийг цэгцлэх.
 *
 * Модуль болгож бичсэн нь `lib/workspaceKind.mjs`-ийн шалтгаантай ижил —
 * дүрмийг нэг газар уншиж, шалгаж болохын тулд. Энд орчуулгын хүснэгт байгаа
 * тул онцгой хэрэгтэй: галиглалын алдаа нь маягт дээр биш, байгууллагын URL,
 * OAuth audience, токены `tenant_slug` claim дээр гарч ирнэ.
 *
 * Санал л болгодог гэдгийг тэмдэглэх нь чухал: setup.go:371-ийн шийдвэрээр
 * кирилл нэрнээс галиглах нь таамаг тул хүн засах эрхтэй, Core-оос ирсэн
 * санал (регистрийн дугаар) энэнээс давуу.
 */

/**
 * Кирилл үсгийн латин дүйцэл (MNS 5217:2012-ын үсэг тус бүрийн харгалзаа).
 *
 * `ө`, `ү` хоёр нь стандартаараа `ö`, `ü` боловч богино нэр ASCII байх ёстой
 * тул `o`, `u` болно. `ъ`, `ь` хоёр хоосон — тэдгээр нь авиа биш тэмдэг. `е`
 * нь үгийн эхэнд `ye`, дотор нь `e`: «Систем» бол `sistem`, `sistyem` биш.
 */
const CYRILLIC_TO_LATIN = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "yo", ж: "j", з: "z",
  и: "i", й: "i", к: "k", л: "l", м: "m", н: "n", о: "o", ө: "o", п: "p",
  р: "r", с: "s", т: "t", у: "u", ү: "u", ф: "f", х: "kh", ц: "ts", ч: "ch",
  ш: "sh", щ: "sh", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/**
 * Байгууллагын хуулийн хэлбэр. Нэрийн үгсийн дундаас хасагдана: `ххк` нь
 * галиглахад `khkhk` болох бөгөөд URL-д ямар ч утга нэмэхгүй.
 */
const LEGAL_FORMS = new Set(["ххк", "хк", "тбб", "ббсб", "нхн", "llc", "jsc", "ltd", "co", "inc"]);

/** Кирилл бичвэрийг латин болгоно; латин тэмдэгт хэвээрээ үлдэнэ. */
function transliterate(text) {
  return [...text.toLowerCase()]
    .map((ch, i, all) => {
      if (ch === "е") {
        // Үгийн эхэнд `ye`, эс бөгөөс `e`.
        const before = i === 0 ? "" : all[i - 1];
        return /[a-zа-яёөү0-9]/i.test(before) ? "e" : "ye";
      }
      return CYRILLIC_TO_LATIN[ch] ?? ch;
    })
    .join("");
}

/**
 * Талбарт бичсэнийг богино нэрийн хэлбэрт оруулна: кирилл нь латин, том үсэг
 * жижиг, зөвшөөрөгдөөгүй тэмдэг бүр зураас, давхар зураас нэг болно.
 *
 * Төгсгөлийн зураасыг хэвээр үлдээнэ — хүн `gerege-nexus` гэж бичиж байхад
 * зураас нь бичих болгонд алга болвол дунд нь зураас оруулах аргагүй болно.
 * Эхлэлийн зураас нь эсрэгээрээ хэзээ ч зөв биш тул тэр даруй хасагдана.
 */
export function normaliseSlugInput(value) {
  return transliterate(value)
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^-+/, "")
    .slice(0, 64);
}

/**
 * Байгууллагын нэрнээс богино нэрийг санал болгоно.
 *
 * Санал л болгож байгаа: хүн талбарт гар хүрмэгц энэ дахин ажиллахгүй бөгөөд
 * бичсэн зүйл нь эцсийн (page.tsx-ийн `slugTouched`). Кирилл нэрнээс галиглах
 * нь таамаг гэдгийг setup.go:371 хэлдэг бөгөөд тийм ч учраас Core-оос ирсэн
 * саналыг (регистрийн дугаар — цор ганц, дүрэмд нийцсэн) энэ дарж бичихгүй.
 */
export function slugFromName(name) {
  const words = name
    .toLowerCase()
    .split(/[^0-9a-zа-яёөү]+/i)
    .filter((word) => word && !LEGAL_FORMS.has(word));
  return normaliseSlugInput(words.join("-")).replace(/-+$/, "");
}
