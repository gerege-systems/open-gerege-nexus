/**
 * Энэ суулгац хүнийг өөрөө таидаг уу, эсвэл өөр газар таидаг уу.
 *
 * Landing page-ийн hero нь eID-ийн картыг өөртөө агуулдаг — платформ өөрөө
 * нэвтрүүлдэг бол зөв зүйл. SSO клиент болсон суулгацад тэр карт худал:
 * `/api/v1/auth/eid/*` нь `requireLocalLogin`-ий цаана байдаг тул 403
 * хариулна. Зочин регистрийн дугаараа бичээд, товч дараад, юу ч болохгүй.
 *
 * Тиймээс энэ асуулт. Хариу нь `/login`-ий асуудаг яг тэр эх сурвалжаас —
 * хоёр дэлгэц нэвтрэлтийн тухай өөр өөр хариулт хэлэх ёсгүй.
 *
 * Серверийн зүгээс асуух нь `lib/storefront.ts`-ийн шалтгаанаар: клиент
 * талд асуувал карт нэг зурагдаад дараа нь алга болно, JS ажиллуулдаггүй
 * робот зөвхөн эхнийхийг нь харна.
 */

/**
 * Дотоод нэвтрэлт боломжтой юу.
 *
 * Аливаа алдаанд `true` — өнөөг хүртэлх зан төлөв. Fetch унасан учраас
 * нэвтрэх картаа нуудаг хуудас нь картаа харуулдаг хуудаснаас дор:
 * эхнийх нь зочныг гарцгүй үлдээнэ, сүүлийнх нь хамгийн муудаа 403.
 */
export async function localSignInEnabledOnServer(): Promise<boolean> {
  const base = process.env.API_INTERNAL_URL;
  if (!base) return true;
  try {
    const res = await fetch(`${base.replace(/\/$/, "")}/auth/sso/config`, {
      // Нэвтрэлтийн чиглэл нь .env-ийн мөр бөгөөд дахин асаахад л
      // өөрчлөгдөнө. Минут тутам асуух нь хангалттай хурдан.
      next: { revalidate: 60 },
    });
    if (!res.ok) return true;
    const cfg = (await res.json()) as { enabled?: boolean; local_login?: boolean };
    // Federation унтраалттай суулгац бол дотоод нэвтрэлт нь цорын ганц зам,
    // `local_login` юу ч гэж хэлсэн бай.
    return !(cfg.enabled === true && cfg.local_login === false);
  } catch {
    return true;
  }
}
