/// Lightweight XOR string obfuscation (SEC-3). Keeps sensitive constants
/// (code-sign requirement, instrumentation library names, SPKI pins) out of
/// `strings <binary>`. NOT cryptographic — a deterrent against casual
/// inspection. Decoded lazily at the point of use.
struct Obfuscated {
    private let bytes: [UInt8]
    init(_ bytes: [UInt8]) { self.bytes = bytes }
    func reveal() -> String {
        var out = [UInt8](); out.reserveCapacity(bytes.count)
        for (i, b) in bytes.enumerated() { out.append(b ^ Obfuscated.key[i % Obfuscated.key.count]) }
        return String(decoding: out, as: UTF8.self)
    }
