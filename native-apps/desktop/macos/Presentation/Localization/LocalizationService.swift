import Foundation
import SwiftUI

/// App display language. Mirrors the Windows `ILocalizationService` cultures
/// (mn-MN / en-US / ru-RU / zh-CN).
enum AppLanguage: String, CaseIterable, Sendable, Identifiable {
    case mn
    case en
    case ru
    case zh
    case fr
    case es
    case ar

    var id: String { rawValue }

    /// Native display name shown in the Settings picker.
    var displayName: String {
        switch self {
        case .mn: return "Монгол"
        case .en: return "English"
        case .ru: return "Русский"
        case .zh: return "中文"
        case .fr: return "Français"
        case .es: return "Español"
        case .ar: return "العربية"
        }
    }

    /// Баруунаас зүүн бичиглэл (араб) — SwiftUI-ийн layoutDirection-д (docs/I18N.md).
    var isRTL: Bool { self == .ar }

    /// Windows culture this language maps to (the .resw folder it was generated from).
    var culture: String {
        switch self {
        case .mn: return "mn-MN"
        case .en: return "en-US"
        case .ru: return "ru-RU"
        case .zh: return "zh-CN"
        case .fr: return "fr-FR"
        case .es: return "es-ES"
        case .ar: return "ar-SA"
        }
    }

    /// `Locale` identifier for date/number formatting (DateFormatter etc.).
    var localeIdentifier: String {
        switch self {
        case .mn: return "mn_MN"
        case .en: return "en_US"
        case .ru: return "ru_RU"
        case .zh: return "zh_Hans"
        case .fr: return "fr_FR"
        case .es: return "es_ES"
        case .ar: return "ar"
        }
    }
}

/// Windows `ILocalizationService` port — holds the current language, persists the
/// selection, and resolves string keys against `L10nCatalog`. `@Published language`
/// drives live SwiftUI re-render when the user switches in Settings, so the whole
/// UI updates in place without a relaunch (matching the Windows `CultureChanged`
/// behaviour).
@MainActor
final class LocalizationService: ObservableObject {
    static let shared = LocalizationService()

    private static let defaultsKey = "app_language"

    @Published private(set) var language: AppLanguage

    init() {
        if let raw = UserDefaults.standard.string(forKey: Self.defaultsKey),
           let lang = AppLanguage(rawValue: raw) {
            language = lang
        } else {
            // App's primary language is Mongolian — default there.
            language = .mn
        }
    }

    func setLanguage(_ lang: AppLanguage) {
        guard lang != language else { return }
        language = lang
        UserDefaults.standard.set(lang.rawValue, forKey: Self.defaultsKey)
    }

    /// Resolve a localization key. Looks in the generated catalog, then the
    /// macOS-only extras, then falls back to Mongolian, then the raw key.
    func string(_ key: String) -> String {
        if let value = Self.catalog(for: language)[key] { return value }
        if let value = Self.extras(for: language)[key] { return value }
        if let fallback = L10nCatalog.mn[key] ?? Self.extraMn[key] { return fallback }
        return key
    }

    private static func catalog(for language: AppLanguage) -> [String: String] {
        switch language {
        case .mn: return L10nCatalog.mn
        case .en: return L10nCatalog.en
        case .ru: return L10nCatalog.ru
        case .zh: return L10nCatalog.zh
        case .fr: return L10nCatalog.fr
        case .es: return L10nCatalog.es
        case .ar: return L10nCatalog.ar
        }
    }

    private static func extras(for language: AppLanguage) -> [String: String] {
        switch language {
        case .mn: return extraMn
        case .en: return extraEn
        case .ru: return extraRu
        case .zh: return extraZh
        case .fr: return extraFr
        case .es: return extraEs
        case .ar: return extraAr
        }
    }

    /// Short alias for `string(_:)`.
    func t(_ key: String) -> String { string(key) }

    /// Inline four-way literal. The web-parity dashboard pages and SignView keep
    /// their copy inline (mirroring the Next.js pages' own inline strings) rather
    /// than in the generated catalog — this is the switch those call sites use.
    /// Шинэ хэлүүд (fr/es/ar) сонголтот: өгөөгүй бол АНГЛИ руу унана. Эдгээр нь дэлгэц
    /// дотор бичигдсэн урт хуулбар текстүүд — каталогид биш (docs/I18N.md).
    func pick(_ mn: String, _ en: String, _ ru: String, _ zh: String,
              fr: String? = nil, es: String? = nil, ar: String? = nil) -> String {
        switch language {
        case .mn: return mn
        case .en: return en
        case .ru: return ru
        case .zh: return zh
        case .fr: return fr ?? en
        case .es: return es ?? en
        case .ar: return ar ?? en
        }
    }

